"""Generate the filter table and authored PPD from factual media dimensions."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ('width', 'height', 'printable_width', 'printable_height', 'x', 'y', 'right', 'code', 'length', 'strips', 'continuous')


def generated_files():
    media = json.loads((ROOT / 'src/media.json').read_text())
    header = ['/* SPDX-License-Identifier: GPL-3.0-only */', '/* Generated by src/generate_media.py; edit src/media.json. */', 'static const media_t media[] = {']
    for m in media:
        assert m['width'] >= m['x'] + m['printable_width'] * m['strips']
        assert m['height'] >= m['y'] + m['printable_height']
        assert m['right'] + m['printable_width'] <= 1296
        header.append('    {' + json.dumps(m['name']) + ', ' + ', '.join(str(m[k]) for k in FIELDS) + '},')
    header.append('};')
    ppd = '''*PPD-Adobe: "4.3"
*% SPDX-License-Identifier: GPL-3.0-only
*% Authored from factual media dimensions; generated by src/generate_media.py.
*FormatVersion: "4.3"
*FileVersion: "0.2.0"
*LanguageVersion: English
*LanguageEncoding: ISOLatin1
*PCFileName: "QL1100N.PPD"
*Manufacturer: "Brother"
*Product: "(QL-1100)"
*ModelName: "Brother QL-1100 Native"
*ShortNickName: "QL-1100 Native"
*NickName: "Brother QL-1100 Native ARM64 0.2"
*PSVersion: "(3010.000) 0"
*LanguageLevel: "3"
*ColorDevice: False
*DefaultColorSpace: Gray
*FileSystem: False
*Throughput: "20"
*LandscapeOrientation: Plus90
*TTRasterizer: Type42
*cupsVersion: 2.0
*cupsManualCopies: True
*cupsFilter: "application/vnd.cups-raster 0 /Library/Printers/QL1100Native/rastertoql1100"
'''.splitlines()
    for keyword, label in [('PageSize', 'Label Size'), ('PageRegion', 'Label Region')]:
        ppd += [f'*OpenUI *{keyword}/{label}: PickOne', f'*OrderDependency: 10 AnySetup *{keyword}', f'*Default{keyword}: w103h164']
        for m in media:
            ppd.append(f'*{keyword} {m["name"]}/{m["label"]}: "<</PageSize[{m["width"]*.24:.2f} {m["height"]*.24:.2f}]/ImagingBBox null>>setpagedevice"')
        ppd.append(f'*CloseUI: *{keyword}')
    for keyword in ('ImageableArea', 'PaperDimension'):
        ppd.append(f'*Default{keyword}: w103h164')
        for m in media:
            dims = [m['width'], m['height']] if keyword == 'PaperDimension' else [m['x'], m['height'] - m['y'] - m['printable_height'], m['x'] + m['printable_width'] * m['strips'], m['height'] - m['y']]
            ppd.append(f'*{keyword} {m["name"]}: "' + ' '.join(f'{d*.24:.2f}' for d in dims) + '"')
    ppd += '''*VariablePaperSize: True
*MaxMediaWidth: "1157.76"
*MaxMediaHeight: "8503.94"
*HWMargins: 0 0 0 0
*CustomPageSize True: "pop pop pop <</PageSize [5 -2 roll] /ImagingBBox null>>setpagedevice"
*ParamCustomPageSize Width: 1 points 34.08 1157.76
*ParamCustomPageSize Height: 2 points 72 8503.93701
*ParamCustomPageSize WidthOffset: 3 points 0 0
*ParamCustomPageSize HeightOffset: 4 points 0 0
*ParamCustomPageSize Orientation: 5 int 0 3
*OpenUI *Resolution/Resolution: PickOne
*OrderDependency: 20 AnySetup *Resolution
*DefaultResolution: 300dpi
*Resolution 300dpi/300 dpi: "<</HWResolution[300 300]>>setpagedevice"
*CloseUI: *Resolution
*OpenUI *ColorModel/Color Mode: PickOne
*OrderDependency: 20 AnySetup *ColorModel
*DefaultColorModel: Black
*ColorModel Black/Monochrome: "<</cupsColorSpace 3/cupsColorOrder 0/cupsBitsPerColor 1>>setpagedevice"
*CloseUI: *ColorModel
*OpenUI *AutoCut/Automatic Cut: Boolean
*OrderDependency: 30 AnySetup *AutoCut
*DefaultAutoCut: True
*AutoCut True/Cut Each Label: ""
*AutoCut False/No Cut: ""
*CloseUI: *AutoCut
*OpenUI *CutEvery/Cut Every: PickOne
*OrderDependency: 30 AnySetup *CutEvery
*DefaultCutEvery: 1
*CutEvery 1/1 Label: ""
*CutEvery 2/2 Labels: ""
*CutEvery 3/3 Labels: ""
*CutEvery 4/4 Labels: ""
*CutEvery 5/5 Labels: ""
*CutEvery 10/10 Labels: ""
*CutEvery 20/20 Labels: ""
*CutEvery 50/50 Labels: ""
*CutEvery 100/100 Labels: ""
*CutEvery 255/255 Labels: ""
*CloseUI: *CutEvery
*OpenUI *CutAtEnd/Cut At Job End: Boolean
*OrderDependency: 30 AnySetup *CutAtEnd
*DefaultCutAtEnd: True
*CutAtEnd True/On: ""
*CutAtEnd False/Off: ""
*CloseUI: *CutAtEnd
*OpenUI *PrintQuality/Print Quality: PickOne
*OrderDependency: 30 AnySetup *PrintQuality
*DefaultPrintQuality: Speed
*PrintQuality Speed/Prioritize Speed: ""
*PrintQuality Quality/Prioritize Quality: ""
*CloseUI: *PrintQuality
*OpenUI *Collate/Collate: Boolean
*OrderDependency: 30 AnySetup *Collate
*DefaultCollate: True
*Collate True/On: ""
*Collate False/Off: ""
*CloseUI: *Collate
*DefaultFont: Courier
*Font Courier: Standard "(001.007)" Standard ROM
'''.splitlines()
    return {'src/media.h': '\n'.join(header) + '\n', 'ppd/Brother-QL1100-Native.ppd': '\n'.join(ppd) + '\n'}


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generated_files().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{name} is stale; run src/generate_media.py')
        else:
            path.write_text(content)
